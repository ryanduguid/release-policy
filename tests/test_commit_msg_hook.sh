#!/usr/bin/env bash
# Exercise .githooks/commit-msg, the local copy of the attribution rules that
# refuses a credit at the keyboard rather than after a push.
#
# The hook and the shared action must agree, and where they differ the hook is
# deliberately the stricter of the two. Every case below is either a parity case
# lifted from tests/test_attribution_action.py or a regression that a previous
# revision of the hook let through.
set -u

HOOK=${1:-$(cd "$(dirname "$0")/.." && pwd)/.githooks/commit-msg}
WORK=$(mktemp -d)
trap 'cd /; rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1
git init -q .

pass=0
fail=0

# run <allow|block> <label> <message> [author-name] [author-email]
#     [committer-name] [committer-email]
run() {
	want=$1
	label=$2
	msg=$3
	an=${4:-Ryan Duguid}
	ae=${5:-ryan@duguid.com.au}
	cn=${6:-$an}
	ce=${7:-$ae}
	printf '%s\n' "$msg" >msg.txt
	if GIT_AUTHOR_NAME="$an" GIT_AUTHOR_EMAIL="$ae" \
		GIT_COMMITTER_NAME="$cn" GIT_COMMITTER_EMAIL="$ce" \
		"$HOOK" msg.txt >/dev/null 2>err.txt; then
		verdict=allow
	else
		verdict=block
	fi
	if [ "$verdict" = "$want" ]; then
		pass=$((pass + 1))
		printf 'ok   %-6s %s\n' "$want" "$label"
	else
		fail=$((fail + 1))
		printf 'FAIL want=%-6s got=%-6s %s\n' "$want" "$verdict" "$label"
		sed 's/^/         /' err.txt | head -3
	fi
}

