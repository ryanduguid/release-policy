	'Ryan Duguid' 'ryan@duguid.com.au' "$(printf 'Ryan\tDuguid')" 'ryan@duguid.com.au'

echo "--- messages that must be allowed ---"
run allow "product reference in a subject" 'feat: publish the skills as a Claude Code plugin'
